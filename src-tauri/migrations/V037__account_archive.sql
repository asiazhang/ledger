-- V037：账户归档标志列 is_archived（spec #1952 / ADR-0142）。加列只增，
-- 不改任何既有对象、零 BREAKING。
--
-- 归档是账户的**收纳态**：只收窄「账户页主表」与「新建 / 编辑的选择面」两处
-- 呈现，不改任何金额口径——余额、余额合计、净资产、报表、投资与目标读数一律
-- 照旧计入归档账户；指向归档账户的进行中计划照常执行、AI 导入照常落账。要让
-- 借出款退出净资产，走既有坏账核销（余额调整归零），不靠归档。
--
-- 与既有两个布尔标志同形同义域（V001）：is_deleted（软删）、is_hidden（黑洞
-- 隐藏）。归档是独立的第三态语义，不复用黑洞隐藏标志（其「同币种最早一行隐藏」
-- 硬绑定与「不进名称映射」的设计都会被复用破坏，ADR-0142 决策 2）；不新增归档
-- 时间戳（行上 updated_at 已有，当前无消费者）。
--
-- 读面零过滤：账户读命令继续返回归档账户（带标志）——名称映射必须拿到归档
-- 账户，「历史照常显示名字」才成立；排除只发生在前端选项构造层（ADR-0142
-- 决策 4）。

ALTER TABLE accounts ADD COLUMN is_archived INTEGER NOT NULL DEFAULT 0 CHECK(is_archived IN (0, 1));
