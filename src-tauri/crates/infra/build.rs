use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    println!("cargo:rerun-if-changed=../../migrations");

    let manifest_dir =
        PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR 未设置"));
    let chain = scan_migrations_dir(&manifest_dir.join("../../migrations"));
    write_chain(
        &chain,
        &PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR 未设置")),
    );
}

fn scan_migrations_dir(dir: &Path) -> Vec<(u32, PathBuf)> {
    let mut chain: Vec<(u32, PathBuf)> = Vec::new();
    let mut seen: std::collections::BTreeMap<u32, PathBuf> = Default::default();
    for entry in
        fs::read_dir(dir).unwrap_or_else(|e| panic!("读取迁移目录失败 {}：{e}", dir.display()))
    {
        let path = entry
            .unwrap_or_else(|e| panic!("读取迁移目录项失败：{e}"))
            .path();
        if !path.is_file() {
            continue;
        }
        let name = path
            .file_name()
            .and_then(|n| n.to_str())
            .unwrap_or_else(|| panic!("迁移文件名非 UTF-8：{}", path.display()))
            .to_owned();
        if !name.ends_with(".sql") {
            continue;
        }
        let Some((version, _)) = name
            .strip_suffix(".sql")
            .and_then(|stem| stem.split_once("__"))
            .and_then(|(v, n)| Some((v.strip_prefix("V")?, n)))
            .filter(|(v, n)| {
                !v.is_empty() && v.bytes().all(|b| b.is_ascii_digit()) && !n.is_empty()
            })
        else {
            panic!("迁移文件名不匹配 V<数字>__<名称>.sql：{name}（笔误即漏注册，宁红不静默）");
        };
        let version: u32 = version
            .parse()
            .unwrap_or_else(|e| panic!("迁移版本号解析失败 {name}：{e}"));
        let prev = seen.insert(version, path.clone());
        if let Some(prev) = prev {
            panic!(
                "迁移版本号重复 V{version}：{} 与 {}",
                prev.display(),
                path.display()
            );
        }
        chain.push((version, path));
    }
    chain.sort_by_key(|(v, _)| *v);
    chain
}

fn write_chain(chain: &[(u32, PathBuf)], out_dir: &Path) {
    let mut out = String::new();
    writeln!(
        out,
        "// @generated by crates/infra/build.rs——迁移链投影，勿手改（issue #2199）"
    )
    .unwrap();
    writeln!(out, "pub const MIGRATION_COUNT: usize = {};", chain.len()).unwrap();
    writeln!(out, "pub const MIGRATION_CHAIN: &[&str] = &[").unwrap();
    for (_, path) in chain {
        let path = path
            .canonicalize()
            .unwrap_or_else(|e| panic!("迁移文件路径解析失败 {}：{e}", path.display()));
        let path = path.to_str().expect("迁移文件路径非 UTF-8");
        writeln!(out, "    include_str!({path:?}),").unwrap();
    }
    writeln!(out, "];").unwrap();
    fs::write(out_dir.join("migration_chain.rs"), out).expect("写入 migration_chain.rs 失败");
}
