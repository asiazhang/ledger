//! 壳机制暂住区（ADR-0111 决策 2 / #1130）：只被壳层消费的机制收进本显式分组。
//!
//! 住址口径：**暂住**——四模块的正住址是壳层，随 #1086 P5 壳层收敛迁出；
//! 迁出前文档口径一律写「壳机制暂住」，不得作为基础设施范式被引用
//! （新基础设施模块不得以本组为模仿先例）。
//!
//! 成员（四个，全部只被壳层消费）：
//! - [`read_entry`]：壳层统一读入口（ADR-0104，spec #1009 批次①）；
//! - [`write_entry`]：壳层统一写入口（ADR-0073，spec #523）；
//! - [`redact`]：IPC 载荷脱敏（ADR-0075 后果条款，issue #1087 首位成员）；
//! - [`logger`]：日志初始化、滚动清理与运行期档位接管（spec #608 / #611）。
//!
//! 分组边界：失效信号投递机制（`events`）与 `DbState` 的消费方跨出壳层
//! （备份域、同步域），**不在本组**，留在共享接缝（ADR-0111 决策 2）。
//!
//! 既有调用点路径零改动：四模块经 crate 根再导出保持 `crate::read_entry::…`
//! 等原路径（本 crate `lib.rs` 与根包两层再导出均不动），域与壳层调用点
//! 零改动即可编译；接缝契约——发射时序、锁失败归一化、`Outcome` 证据形态、
//! 组合语义（ADR-0073 / ADR-0104）——逐条不变。

pub mod logger;
