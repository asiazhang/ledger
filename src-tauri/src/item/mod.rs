//! 物品（Item）领域模块（spec #113 / ADR-0014）。
//!
//! 职责：耐用实物物品的创建、修改、处置、软删除、列表与「每天使用成本」
//! 读取聚合——写入口的归一化与校验、溯源准入、口径接线与失效信号回调注入。
//!
//! 接缝：
//! - [`cost`]（DailyUsageCost 权威）：「每天使用成本」纯计算，分子（总成本 − 残值）
//!   ÷ 分母（购买日 → 目标日的日历天数，含起止两端）。
//! - [`domain`]（域 API，单一权威）：写路径（创建/修改/处置/删除）与读路径
//!   （列表/单件每天成本/在用合计）七项，域语言短名；失效信号以 `notify`
//!   回调注入（回调注入式，仿 `commands::sync` 的 emit 注入先例）。
//! - [`guard`]（溯源守卫，ADR-0025 创建唯一入口的准入接缝）：关联购买交易的
//!   解析、校验与自动带出——溯源必填/唯一在创建时刻强制。
//!
//! 依赖方向恒为「壳层 → item → 基础设施」：本模块不反向依赖壳层；
//! 对 `transaction::amount` 的消费属域间横向依赖（ADR-0056 决策 2 允许）。

